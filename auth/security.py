"""
Лабораторная работа №1. Защита информации на основе механизмов
идентификации и двухфакторной аутентификации.

Модуль реализует криптографические примитивы для двухфакторной
аутентификации (2FA):

  1) первый фактор — многоразовый пароль пользователя. Пароль никогда
     не хранится в открытом виде: хранится "соль" + PBKDF2-HMAC-SHA256
     свёртка (200 000 итераций), что соответствует рекомендациям из
     методических указаний (табл. 2: "хеширование паролей");

  2) второй фактор — одноразовый код (OTP), отправляемый пользователю
     на его электронную почту (см. auth/email_service.py). Код, как и
     пароль, никогда не хранится в БД в открытом виде — хранится только
     его свёртка (та же функция hash_password/verify_password), что
     исключает восстановление действующего кода при утечке базы данных.

Все примитивы построены на модулях стандартной библиотеки Python
(hashlib, hmac, secrets) — сторонние библиотеки не используются.
"""

import hashlib
import hmac
import secrets

# ---------------------------------------------------------------------------
# Параметры первого фактора (пароль)
# ---------------------------------------------------------------------------
PBKDF2_ITERATIONS = 200_000
SALT_SIZE = 16  # байт


def hash_password(password: str, salt: bytes = None) -> tuple:
    """Возвращает (hash_hex, salt_hex) — свёртку секрета (пароля или
    одноразового кода) и соль, с которой она была вычислена. Функция
    универсальна: используется и для пароля (первый фактор), и для
    одноразового кода (второй фактор), так как в обоих случаях задача
    одна — не хранить секрет в открытом виде."""
    if salt is None:
        salt = secrets.token_bytes(SALT_SIZE)
    digest = hashlib.pbkdf2_hmac('sha256', password.encode('utf-8'), salt, PBKDF2_ITERATIONS)
    return digest.hex(), salt.hex()


def verify_password(password: str, salt_hex: str, hash_hex: str) -> bool:
    """Проверяет секрет сравнением свёрток за постоянное время
    (hmac.compare_digest защищает от атак по времени ответа)."""
    salt = bytes.fromhex(salt_hex)
    candidate_hash, _ = hash_password(password, salt)
    return hmac.compare_digest(candidate_hash, hash_hex)


# ============================== ВТОРОЙ ФАКТОР ===============================
# Одноразовый код, отправляемый на электронную почту пользователя.

def generate_otp_code(digits: int = 6) -> str:
    """Генерирует случайный числовой одноразовый код заданной длины,
    используя криптографически стойкий генератор secrets (а не random!),
    чтобы код нельзя было предсказать."""
    return ''.join(secrets.choice('0123456789') for _ in range(digits))
